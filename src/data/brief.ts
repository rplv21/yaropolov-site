// Бриф на создание сайта: единый источник вопросов.
// Из него строятся и онлайн-форма (/brief), и PDF, который уходит в Telegram,
// поэтому текст вопросов, варианты и порядок меняются только здесь.

export type BriefType = 'text' | 'long' | 'radio' | 'checks';

export interface BriefItem {
  id: string; // q1_1, q1_2 ...
  n: string; // «1.1»
  q: string;
  h?: string;
  type: BriefType;
  options?: string[];
  required?: boolean;
  mask?: 'phone';
  inputType?: 'tel' | 'email';
}

export interface BriefSection {
  id: string;
  n: number;
  title: string;
  items: BriefItem[];
}

type Raw = Omit<BriefItem, 'id' | 'n'>;

const make = (sections: { title: string; items: Raw[] }[]): BriefSection[] =>
  sections.map((s, si) => ({
    id: `s${si + 1}`,
    n: si + 1,
    title: s.title,
    items: s.items.map((it, ii) => ({ ...it, id: `q${si + 1}_${ii + 1}`, n: `${si + 1}.${ii + 1}` })),
  }));

